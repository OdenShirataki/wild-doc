/// Lazily loaded sources that are not in the snapshot. Generated by build.rs.
mod residual_sources {
    include!(concat!(env!("OUT_DIR"), "/residual_sources.rs"));
}

/// A search result handed to JavaScript.
enum Held {
    Search(Arc<SearchResult>),
    Session(Arc<SessionSearchResult>),
}

/// State shared with the functions that wild-doc adds to JavaScript.
///
/// JavaScript objects of search results only hold an index into `results`,
/// so the results stay alive as long as the worker does, even if a script
/// keeps the objects longer than the variables that held them.
struct State {
    /// The stack of the running `eval` / `evaluate_module`, or null.
    stack: Cell<*const Stack>,
    results: RefCell<Vec<Held>>,
    include: IncludeFn,
}

/// Reads an included file through the include adaptor of wild-doc.
type IncludeFn = Box<dyn Fn(&Path) -> Option<Arc<Vec<u8>>>>;

pub struct Deno {
    // Declared before `state`, so the worker (and every JavaScript function
    // that points to the state) is dropped first.
    worker: MainWorker,
    state: Box<State>,
}

const RESULT_INDEX_KEY: &str = "wd_result_index";

/// Returns the state from the data of a function made by [new_function].
fn state<'a>(args: &v8::FunctionCallbackArguments) -> Option<&'a State> {
    let data = args.data().try_cast::<v8::External>().ok()?;
    // SAFETY: every function made by `new_function` has a pointer to the
    // boxed `State` of its `Deno` as data, and the state outlives the worker.
    Some(unsafe { &*(data.value() as *const State) })
}

fn new_function<'s>(
    scope: &mut v8::PinScope<'s, '_>,
    state: &State,
    callback: impl v8::MapFnTo<v8::FunctionCallback>,
) -> Option<v8::Local<'s, v8::Function>> {
    let data = v8::External::new(scope, state as *const State as *mut c_void);
    v8::Function::builder(callback)
        .data(data.into())
        .build(scope)
}

fn set<'s>(
    scope: &mut v8::PinScope<'s, '_>,
    obj: v8::Local<'s, v8::Object>,
    key: &str,
    value: v8::Local<'s, v8::Value>,
) -> Option<()> {
    let key = v8::String::new(scope, key)?;
    obj.set(scope, key.into(), value)?;
    Some(())
}

/// Makes `{ rows: [...], join(key, row) }` for a search result.
fn held_to_v8<'s>(
    scope: &mut v8::PinScope<'s, '_>,
    state: &State,
    held: Held,
) -> Option<v8::Local<'s, v8::Value>> {
    let mut rows: Vec<v8::Local<v8::Value>> = vec![];
    match &held {
        Held::Search(result) => {
            for row in result.rows() {
                rows.push(v8::Integer::new_from_unsigned(scope, row.get()).into());
            }
        }
        Held::Session(result) => {
            for row in result.rows() {
                rows.push(v8::BigInt::new_from_i64(scope, row.get()).into());
            }
        }
    }
    let index = {
        let mut results = state.results.borrow_mut();
        results.push(held);
        results.len() - 1
    };

    let obj = v8::Object::new(scope);
    let rows = v8::Array::new_with_elements(scope, &rows);
    set(scope, obj, "rows", rows.into())?;
    let join = new_function(scope, state, join)?;
    set(scope, obj, "join", join.into())?;

    let name = v8::String::new(scope, RESULT_INDEX_KEY)?;
    let key = v8::Private::for_api(scope, Some(name));
    let index = v8::Number::new(scope, index as f64);
    obj.set_private(scope, key, index.into())?;

    Some(obj.into())
}

/// `result.join(key, row)`: returns the joined result of the row.
fn join(scope: &mut v8::PinScope, args: v8::FunctionCallbackArguments, mut rv: v8::ReturnValue) {
    let Some(state) = state(&args) else {
        return;
    };
    let Some(name) = v8::String::new(scope, RESULT_INDEX_KEY) else {
        return;
    };
    let key = v8::Private::for_api(scope, Some(name));
    let Some(index) = args
        .this()
        .get_private(scope, key)
        .and_then(|v| v.uint32_value(scope))
    else {
        return;
    };
    let join_key = args.get(0).to_rust_string_lossy(scope);
    let row = args.get(1);

    // the index is checked against the list, so a changed index is harmless.
    let child = match state.results.borrow().get(index as usize) {
        Some(Held::Search(result)) => row
            .uint32_value(scope)
            .and_then(NonZeroU32::new)
            .and_then(|row| result.join().get(&join_key)?.get(&row).cloned())
            .map(|r| Held::Search(Arc::new(r))),
        Some(Held::Session(result)) => row
            .integer_value(scope)
            .and_then(NonZeroI64::new)
            .and_then(|row| result.join().get(&join_key)?.get(&row).cloned())
            .map(|r| Held::Session(Arc::new(r))),
        None => None,
    };
    if let Some(value) = child.and_then(|child| held_to_v8(scope, state, child)) {
        rv.set(value);
    }
}

fn wd2v8<'s>(
    scope: &mut v8::PinScope<'s, '_>,
    state: &State,
    value: &WildDocValue,
) -> Option<v8::Local<'s, v8::Value>> {
    match value {
        WildDocValue::Binary(v) => {
            let store = v8::ArrayBuffer::new_backing_store_from_vec(v.to_owned()).make_shared();
            let buffer = v8::ArrayBuffer::with_backing_store(scope, &store);
            v8::Uint8Array::new(scope, buffer, 0, buffer.byte_length()).map(Into::into)
        }
        WildDocValue::Object(map) => {
            let obj = v8::Object::new(scope);
            for (key, value) in map {
                if let Some(value) = wd2v8(scope, state, value) {
                    set(scope, obj, key, value);
                }
            }
            Some(obj.into())
        }
        WildDocValue::SearchResult(result) => {
            held_to_v8(scope, state, Held::Search(Arc::clone(result)))
        }
        WildDocValue::SessionSearchResult(result) => {
            held_to_v8(scope, state, Held::Session(Arc::clone(result)))
        }
        _ => serde_v8::to_v8(scope, value).ok(),
    }
}

/// `wd.v(name)`: returns a variable of wild-doc.
fn v(scope: &mut v8::PinScope, args: v8::FunctionCallbackArguments, mut rv: v8::ReturnValue) {
    let Some(state) = state(&args) else {
        return;
    };
    let stack = state.stack.get();
    if stack.is_null() {
        return;
    }
    // SAFETY: `stack` is set from the `&Stack` of the running call and reset
    // to null when the call returns.
    let stack = unsafe { &*stack };
    let key = args.get(0).to_rust_string_lossy(scope);
    if let Some(value) = stack.get(&Arc::new(key))
        && let Some(value) = wd2v8(scope, state, value)
    {
        rv.set(value);
    }
}

/// `wd.get_contents(path)`: returns the contents of an included file.
fn get_contents(
    scope: &mut v8::PinScope,
    args: v8::FunctionCallbackArguments,
    mut rv: v8::ReturnValue,
) {
    let Some(state) = state(&args) else {
        return;
    };
    let filename = args.get(0).to_rust_string_lossy(scope);
    if let Some(contents) = (state.include)(Path::new(&filename))
        && let Ok(value) = serde_v8::to_v8(scope, contents.as_slice())
    {
        rv.set(value);
    }
}

#[async_trait(?Send)]
impl<I: IncludeAdaptor + Send + 'static> WildDocScript<I> for Deno {
    fn new(include_adaptor: Arc<Mutex<I>>, cache_dir: PathBuf, _: &Stack) -> Result<Self> {
        v8::V8::set_flags_from_string("--stack_size=10240");

        let mut worker = MainWorker::bootstrap_from_options(
            &deno_core::resolve_url("wd://main")?,
            WorkerServiceOptions::<DenoInNpmPackageChecker, NpmResolver<RealSys>, RealSys> {
                blob_store: Arc::new(BlobStore::default()),
                broadcast_channel: Default::default(),
                deno_rt_native_addon_loader: None,
                feature_checker: Default::default(),
                fs: Arc::new(RealFs),
                module_loader: Rc::new(WdModuleLoader::new(cache_dir)),
                node_services: None,
                npm_process_state_provider: None,
                permissions: PermissionsContainer::allow_all(Arc::new(
                    RuntimePermissionDescriptorParser::new(RealSys),
                )),
                root_cert_store_provider: None,
                fetch_dns_resolver: Default::default(),
                shared_array_buffer_store: None,
                compiled_wasm_module_store: None,
                v8_code_cache: None,
                bundle_provider: None,
            },
            WorkerOptions {
                startup_snapshot: Some(include_bytes!(concat!(env!("OUT_DIR"), "/runtime.bin"))),
                residual_lazy_js_sources: residual_sources::RESIDUAL_LAZY_JS_SOURCES,
                residual_lazy_esm_sources: residual_sources::RESIDUAL_LAZY_ESM_SOURCES,
                ..Default::default()
            },
        );

        let state = Box::new(State {
            stack: Cell::new(std::ptr::null()),
            results: RefCell::new(vec![]),
            include: Box::new(move |path| include_adaptor.lock().include(path)),
        });

        let wd = worker.execute_script(
            "<wd>",
            deno_core::ascii_str!("globalThis.wd = { general: {} }; wd").into(),
        )?;
        {
            deno_core::scope!(scope, worker.js_runtime);
            let wd = v8::Local::new(scope, wd)
                .to_object(scope)
                .ok_or_else(|| anyhow!("failed to create wd"))?;
            let v = new_function(scope, &state, v).ok_or_else(|| anyhow!("wd.v"))?;
            set(scope, wd, "v", v.into());
            let get_contents = new_function(scope, &state, get_contents)
                .ok_or_else(|| anyhow!("wd.get_contents"))?;
            set(scope, wd, "get_contents", get_contents.into());
        }
        Ok(Self { worker, state })
    }

    async fn evaluate_module(&mut self, file_name: &str, src: &str, stack: &Stack) -> Result<()> {
        let specifier = ModuleSpecifier::parse(&format!("wd://script{file_name}"))?;
        self.state.stack.set(stack);
        let result = async {
            let id = self
                .worker
                .js_runtime
                .load_side_es_module_from_code(&specifier, src.to_owned())
                .await?;
            self.worker.evaluate_module(id).await?;
            Ok(())
        }
        .await;
        self.state.stack.set(std::ptr::null());
        result
    }

    async fn eval(&mut self, code: &str, stack: &Stack) -> Result<WildDocValue> {
        self.state.stack.set(stack);
        let result = self.worker.execute_script("<anon>", code.to_owned().into());
        self.state.stack.set(std::ptr::null());
        let Ok(value) = result else {
            return Ok(WildDocValue::Null);
        };

        deno_core::scope!(scope, self.worker.js_runtime);
        let value = v8::Local::new(scope, value);
        if let Ok(view) = v8::Local::<v8::ArrayBufferView>::try_from(value) {
            let mut bytes = vec![0; view.byte_length()];
            let len = view.copy_contents(&mut bytes);
            bytes.truncate(len);
            return Ok(WildDocValue::Binary(bytes));
        }
        Ok(serde_v8::from_v8::<serde_json::Value>(scope, value)
            .map(Into::into)
            .unwrap_or(WildDocValue::Null))
    }
}
